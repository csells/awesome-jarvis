"""Build the review dropdown from the installed Pocket catalog and verified custom samples."""
import ast,json,pathlib,concurrent.futures,argparse
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--pocket-source',type=pathlib.Path,required=True,help='Pocket source checkout')
parser.add_argument('--output',type=pathlib.Path,default=pathlib.Path(__file__).parent)
parser.add_argument('--cache',type=pathlib.Path,default=pathlib.Path.home()/'.cache/pocket-preview')
args=parser.parse_args()
D=args.output;D.mkdir(parents=True,exist_ok=True)
source=args.pocket_source/'pocket_tts/utils/utils.py'
tree=ast.parse(source.read_text())
origins=next(ast.literal_eval(n.value) for n in tree.body if isinstance(n,ast.Assign) and any(isinstance(t,ast.Name) and t.id=='_ORIGINS_OF_PREDEFINED_VOICES' for t in n.targets))
voices=[{'id':'alfred','name':'Alfred','category':'Custom voices','sample':'alfred.wav','sample_kind':'Generated by our Pocket service'},{'id':'jeremy-irons','name':'Jeremy Irons','category':'Custom voices','sample':'other-voice.wav','sample_kind':'Generated by our Pocket service'}]
assets=D/'voices';assets.mkdir(exist_ok=True)
def download(item):
 name,origin=item;parts=origin.removeprefix('hf://').split('/');repo='/'.join(parts[:2]);path='/'.join(parts[2:]);filename,sep,revision=path.partition('@');revision=revision if sep else 'main'
 url=f'https://huggingface.co/{repo}/resolve/{revision}/{filename}'
 target=assets/(name+pathlib.Path(filename).suffix)
 if not target.exists():
  from huggingface_hub import hf_hub_download
  from huggingface_hub.errors import GatedRepoError
  try:
   cached=hf_hub_download(repo_id=repo,filename=filename,revision=revision,cache_dir=str(args.cache))
  except GatedRepoError:
   print('Reference requires Hugging Face access: '+name,flush=True)
   return {'id':name,'name':name.title(),'category':'Pocket built-in voices','sample':None,'sample_kind':'Reference sample requires Hugging Face access','source':url}
  target.write_bytes(pathlib.Path(cached).read_bytes())
 return {'id':name,'name':name.replace('_',' ').title(),'category':'Pocket built-in voices','sample':'voices/'+target.name,'sample_kind':'Pocket reference sample (not a generated test)','source':url}
with concurrent.futures.ThreadPoolExecutor(max_workers=4) as pool:
 for v in pool.map(download,sorted(origins.items())):
  voices.append(v);print('Fetched '+v['id'],flush=True)
(D/'voices.json').write_text(json.dumps({'voices':voices,'default':'alfred'},indent=2))
print(f'Catalog: {len(voices)} voices',flush=True)
