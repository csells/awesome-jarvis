import {createRequire} from 'node:module';
import {writeFileSync} from 'node:fs';
const require=createRequire('/Users/csells/code/CopilotKit/OpenDots/package.json');
const {chromium}=require('playwright');
const out='/Users/csells/.bb/thread-storage/opendots-test-20261005';
const browser=await chromium.launch({executablePath:'/Users/csells/.chrome-agent/chromium/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing',headless:true});
const results=[];
try{
 const p=await browser.newPage({viewport:{width:1440,height:1000}});
 p.on('pageerror',e=>console.log('PAGE_ERROR',e.message));
 await p.goto('http://127.0.0.1:14310');
 await p.getByRole('button',{name:'Everyday',exact:true}).click();
 await p.getByRole('button',{name:'New page',exact:true}).first().click();
 await p.getByRole('textbox',{name:'Page title'}).fill('Phone workflow test');
 await p.getByRole('button',{name:'Page actions'}).click();
 await p.getByRole('menuitem',{name:'Markdown source',exact:true}).click();
 await p.getByRole('textbox',{name:'Page Markdown'}).fill('The green notebook contains eleven pages.');
 await p.getByRole('textbox',{name:'Page Markdown'}).press('Meta+s');
 await p.getByText('All changes saved',{exact:true}).waitFor({timeout:10000}).catch(async()=>{console.log('SAVE_LABELS',await p.locator('body').innerText());});
 const pageUrl=p.url();
 const ws=await (await p.request.get('http://127.0.0.1:14310/api/workspace')).json();
 const space=ws.spaces.find(x=>x.name==='Everyday');
 const pages=await (await p.request.get('http://127.0.0.1:14310/api/spaces/'+space.id+'/pages')).json();
 const saved=pages.find(x=>x.title==='Phone workflow test');
 if(saved?.content!=='The green notebook contains eleven pages.')throw new Error('Saved content mismatch');
 console.log('PASS desktop page create/save',saved);
 results.push({test:'desktop manual create/save',result:'PASS',saved});
 await p.screenshot({path:out+'/desktop-page.png',fullPage:true});
 const m=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true,deviceScaleFactor:2});
 await m.goto(pageUrl);
 await m.getByRole('textbox',{name:'Page title'}).waitFor();
 if(await m.getByRole('textbox',{name:'Page title'}).inputValue()!=='Phone workflow test')throw new Error('Reload title mismatch');
 await m.getByText('The green notebook contains eleven pages.',{exact:true}).waitFor();
 const layout=await m.evaluate(()=>({innerWidth,scrollWidth:document.documentElement.scrollWidth}));
 results.push({test:'phone viewport persisted page and layout',result:layout.scrollWidth<=layout.innerWidth?'PASS':'FAIL',layout});
 await m.screenshot({path:out+'/mobile-page.png',fullPage:true});
 await m.getByRole('button',{name:'Pause all Dots'}).click();
 await m.getByRole('button',{name:'Resume all Dots'}).waitFor();
 const paused=await(await m.request.get('http://127.0.0.1:14310/api/state')).json();
 results.push({test:'phone pause control',result:paused.settings.paused?'PASS':'FAIL'});
 await m.getByRole('button',{name:'Resume all Dots'}).click();
 const conversation=await m.request.post('http://127.0.0.1:14310/api/conversations',{data:{dotId:ws.dots[0].id,title:'Lab call check'}});
 results.push({test:'stock conversation setup gate',status:conversation.status(),body:await conversation.json(),result:'BLOCKED'});
 const voice=await m.request.post('http://127.0.0.1:14310/api/voice/calls',{data:{threadId:'lab-not-created',sdp:'v=0\r\nm=audio 9 UDP/TLS/RTP/SAVPF 111'}});
 results.push({test:'stock voice setup gate',status:voice.status(),body:await voice.json(),result:'BLOCKED'});
 writeFileSync(out+'/ui-workflows.json',JSON.stringify(results,null,2));
 console.log(JSON.stringify(results,null,2));
}finally{await browser.close()}
